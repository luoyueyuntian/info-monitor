"""Backtest service for evaluating event rules against historical data.

Loads historical normalized records, runs detectors and event rules,
returns hypothetical events without persisting them.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from datetime import datetime
from typing import Any, Dict, List, Optional

from sqlalchemy import text
from sqlalchemy.engine import Connection

from info_monitor_worker.db import create_db_engine
from info_monitor_worker.detectors import get_detector
from info_monitor_worker.event_rules.boll_signal import BOLLSignalRule
from info_monitor_worker.event_rules.financial_direction import FinancialDirectionRule
from info_monitor_worker.event_rules.kdj_signal import KDJSignalRule
from info_monitor_worker.event_rules.macd_signal import MACDSignalRule
from info_monitor_worker.event_rules.moving_average_signal import MovingAverageSignalRule
from info_monitor_worker.event_rules.price_30d_low import ThirtyDayLowRule
from info_monitor_worker.event_rules.rsi_signal import RSISignalRule
from info_monitor_worker.models import SourceContext, ThemeContext

logger = logging.getLogger(__name__)


@dataclass
class HypotheticalEvent:
    """An event that would have been generated by the rules."""

    event_type: str
    signal: str
    title: str
    summary: str
    occurred_at: str
    evidence: List[str]


@dataclass
class BacktestResult:
    """Result of a backtest run."""

    source_id: str
    theme_id: str
    start_date: str
    end_date: str
    total_records: int
    hypothetical_events: List[HypotheticalEvent]
    signal_distribution: Dict[str, int]
    timeline: List[Dict[str, Any]]


def _fetch_records_by_date_range(
    connection: Connection,
    source_id: str,
    start_date: str,
    end_date: str,
) -> List[Dict[str, Any]]:
    """Fetch normalized records within a date range."""
    rows = connection.execute(
        text(
            """
            SELECT id, title, occurred_at, content_json, info_type, logical_key, fingerprint
            FROM normalized_records
            WHERE source_id = :source_id
              AND occurred_at >= :start_date
              AND occurred_at <= :end_date
            ORDER BY occurred_at ASC
            """
        ),
        {"source_id": source_id, "start_date": start_date, "end_date": end_date},
    )
    return [dict(row._mapping) for row in rows]


def _fetch_theme_info(connection: Connection, theme_id: str) -> Optional[Dict[str, Any]]:
    """Fetch theme info by ID."""
    rows = connection.execute(
        text("SELECT id, name, info_type FROM themes WHERE id = :theme_id"),
        {"theme_id": theme_id},
    )
    row = rows.fetchone()
    return dict(row._mapping) if row else None


def _fetch_source_info(connection: Connection, source_id: str) -> Optional[Dict[str, Any]]:
    """Fetch source info by ID."""
    rows = connection.execute(
        text(
            "SELECT id, name, source_type, adapter_key, config FROM sources WHERE id = :source_id"
        ),
        {"source_id": source_id},
    )
    row = rows.fetchone()
    return dict(row._mapping) if row else None


def run_backtest(
    source_id: str,
    start_date: str,
    end_date: str,
    detector_config: Optional[Dict[str, Any]] = None,
) -> BacktestResult:
    """Run a backtest against historical data.

    Args:
        source_id: Source to backtest.
        start_date: Start date (ISO format).
        end_date: End date (ISO format).
        detector_config: Optional overrides for detector thresholds.

    Returns:
        BacktestResult with hypothetical events and statistics.
    """
    engine = create_db_engine()

    with engine.begin() as connection:
        source_info = _fetch_source_info(connection, source_id)
        if not source_info:
            raise ValueError(f"Source {source_id} not found")

        theme_id = source_info.get("config", {}).get("theme_id")
        if not theme_id:
            # Try to find theme from normalized records
            rows = connection.execute(
                text(
                    "SELECT theme_id FROM normalized_records WHERE source_id = :sid LIMIT 1"
                ),
                {"sid": source_id},
            )
            row = rows.fetchone()
            theme_id = row[0] if row else None

        if not theme_id:
            raise ValueError(f"Could not determine theme for source {source_id}")

        theme_info = _fetch_theme_info(connection, theme_id)
        if not theme_info:
            raise ValueError(f"Theme {theme_id} not found")

        records = _fetch_records_by_date_range(connection, source_id, start_date, end_date)

    theme = ThemeContext(
        theme_id=theme_info["id"],
        theme_name=theme_info["name"],
        info_type=theme_info["info_type"],
    )
    source = SourceContext(
        source_id=source_info["id"],
        source_name=source_info["name"],
        source_type=source_info.get("source_type", ""),
        adapter_key=source_info.get("adapter_key", ""),
        config=source_info.get("config") or {},
    )

    # Initialize event rules
    price_low_rule = ThirtyDayLowRule()
    financial_direction_rule = FinancialDirectionRule()
    rsi_rule = RSISignalRule()
    macd_rule = MACDSignalRule()
    kdj_rule = KDJSignalRule()
    boll_rule = BOLLSignalRule()
    ma_rule = MovingAverageSignalRule()

    hypothetical_events: List[HypotheticalEvent] = []
    signal_counts: Dict[str, int] = {}
    timeline: List[Dict[str, Any]] = []

    for record in records:
        import json

        content = record.get("content_json", "{}")
        if isinstance(content, str):
            content = json.loads(content)

        # Create a simple object to mimic normalized_record
        class RecordProxy:
            def __init__(self, data: Dict[str, Any], content: Dict[str, Any]):
                self.title = data["title"]
                self.occurred_at = data["occurred_at"]
                self.logical_key = data.get("logical_key")
                self.fingerprint = data.get("fingerprint")
                self.content = content

        proxy = RecordProxy(record, content)

        record_events: List[HypotheticalEvent] = []

        # Evaluate rules based on info_type
        if theme.info_type == "price":
            # Technical indicators
            indicators = content.get("indicators")
            if indicators:
                for rule, event_type in [
                    (rsi_rule, "rsi_signal"),
                    (macd_rule, "macd_signal"),
                    (kdj_rule, "kdj_signal"),
                    (boll_rule, "boll_signal"),
                    (ma_rule, "ma_signal"),
                ]:
                    result = rule.evaluate(proxy)
                    if result.triggered:
                        evt = HypotheticalEvent(
                            event_type=event_type,
                            signal=result.signal,
                            title=result.title,
                            summary=result.summary,
                            occurred_at=record["occurred_at"],
                            evidence=result.evidence,
                        )
                        record_events.append(evt)

            # Price low rule
            result = price_low_rule.evaluate(proxy, None)
            if result.triggered:
                evt = HypotheticalEvent(
                    event_type="price_low",
                    signal=result.signal,
                    title=result.title,
                    summary=result.summary,
                    occurred_at=record["occurred_at"],
                    evidence=result.evidence,
                )
                record_events.append(evt)

        elif theme.info_type == "financial_event":
            result = financial_direction_rule.evaluate(proxy)
            if result.triggered:
                evt = HypotheticalEvent(
                    event_type="financial_direction",
                    signal=result.signal,
                    title=result.title,
                    summary=result.summary,
                    occurred_at=record["occurred_at"],
                    evidence=result.evidence,
                )
                record_events.append(evt)
            else:
                evt = HypotheticalEvent(
                    event_type="new_financial_event",
                    signal="new_financial_event",
                    title=proxy.title,
                    summary=f"New financial event for theme {theme.theme_name}",
                    occurred_at=record["occurred_at"],
                    evidence=[f"Title: {proxy.title}"],
                )
                record_events.append(evt)

        elif theme.info_type in ("news_announcement", "content_update"):
            signal = "new_announcement" if theme.info_type == "news_announcement" else "content_update"
            evt = HypotheticalEvent(
                event_type="new_release",
                signal=signal,
                title=proxy.title,
                summary=f"New {theme.info_type} detected for theme {theme.theme_name}",
                occurred_at=record["occurred_at"],
                evidence=[f"Title: {proxy.title}"],
            )
            record_events.append(evt)

        # Collect results
        for evt in record_events:
            hypothetical_events.append(evt)
            signal_counts[evt.signal] = signal_counts.get(evt.signal, 0) + 1

        timeline.append({
            "record_id": record["id"],
            "occurred_at": record["occurred_at"],
            "title": record["title"],
            "event_count": len(record_events),
            "signals": [e.signal for e in record_events],
        })

    engine.dispose()

    return BacktestResult(
        source_id=source_id,
        theme_id=theme_id,
        start_date=start_date,
        end_date=end_date,
        total_records=len(records),
        hypothetical_events=[
            {
                "event_type": e.event_type,
                "signal": e.signal,
                "title": e.title,
                "summary": e.summary,
                "occurred_at": e.occurred_at,
                "evidence": e.evidence,
            }
            for e in hypothetical_events
        ],
        signal_distribution=signal_counts,
        timeline=timeline,
    )
